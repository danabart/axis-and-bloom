import { computeCatalogHash, declaredWriterModules, parseRelationComment, readCatalogMdHash, CATALOG_HASH_FOOTER } from './dataCatalogQueries.js';
import { extractFirestoreBlock, renderCatalogMd } from './dataCatalogMd.js';
import type { CatalogRow } from './dataCatalogQueries.js';

const GOOD = 'Purpose: One row per coffee. | Class: master | Writer: catalogService.createCoffee | Readers: v_coffee | Since: 2026-05-25';

describe('parseRelationComment', () => {
  it('splits a well-formed comment into the five fields', () => {
    expect(parseRelationComment(GOOD)).toEqual({
      unverified: false,
      purpose: 'One row per coffee.',
      class: 'master',
      writer: 'catalogService.createCoffee',
      readers: 'v_coffee',
      since: '2026-05-25',
      wellFormed: true,
    });
  });

  it('reads past an UNVERIFIED prefix and flags it', () => {
    const p = parseRelationComment(`UNVERIFIED: not in schema.sql | ${GOOD}`);
    expect(p.unverified).toBe(true);
    expect(p.wellFormed).toBe(true);
    expect(p.purpose).toBe('One row per coffee.');
  });

  it('keeps colons inside a field value', () => {
    expect(parseRelationComment(GOOD.replace('One row per coffee.', 'Note: one row per coffee.')).purpose).toBe('Note: one row per coffee.');
  });

  it('is not well-formed with a missing field, fields out of order, an empty field or an unknown Class', () => {
    expect(parseRelationComment('Purpose: x | Class: master | Writer: y | Since: z').wellFormed).toBe(false);
    expect(parseRelationComment('Class: master | Purpose: x | Writer: y | Readers: r | Since: z').wellFormed).toBe(false);
    expect(parseRelationComment('Purpose: x | Class: master | Writer:  | Readers: r | Since: z').wellFormed).toBe(false);
    expect(parseRelationComment('Purpose: x | Class: dimension | Writer: y | Readers: r | Since: z').wellFormed).toBe(false);
    expect(parseRelationComment('just a sentence').wellFormed).toBe(false);
  });
});

describe('computeCatalogHash', () => {
  const rows = [
    { object_type: 'table' as const, table_name: 'a', column_name: null, comment: GOOD },
    { object_type: 'column' as const, table_name: 'a', column_name: 'id', comment: 'Primary key.' },
    { object_type: 'view' as const, table_name: 'v_a', column_name: null, comment: null },
  ];

  it('is a 64-char hex sha256', () => {
    expect(computeCatalogHash(rows)).toMatch(/^[0-9a-f]{64}$/);
  });

  it('does not depend on row order', () => {
    expect(computeCatalogHash([...rows].reverse())).toBe(computeCatalogHash(rows));
  });

  it('changes when a comment changes, an object is added or a column is renamed', () => {
    const base = computeCatalogHash(rows);
    expect(computeCatalogHash([rows[0], { ...rows[1], comment: 'Primary key (uuid).' }, rows[2]])).not.toBe(base);
    expect(computeCatalogHash([...rows, { object_type: 'column', table_name: 'a', column_name: 'x', comment: 'X.' }])).not.toBe(base);
    expect(computeCatalogHash([rows[0], { ...rows[1], column_name: 'uuid' }, rows[2]])).not.toBe(base);
  });
});

describe('CATALOG.md rendering', () => {
  const row = (r: Partial<CatalogRow>): CatalogRow => ({
    object_type: 'table', table_name: 't', column_name: null, data_type: null, is_nullable: null, comment: null,
    purpose: null, class: null, writer: null, readers: null, since: null, is_unverified: false, ordinal_position: 0, ...r,
  });
  const input = {
    rows: [
      row({ table_name: 'coffees', comment: GOOD }),
      row({ object_type: 'column', table_name: 'coffees', column_name: 'id', data_type: 'integer', is_nullable: false, comment: 'Id. | Writer: seed', ordinal_position: 1 }),
      row({ object_type: 'view', table_name: 'v_coffee', comment: GOOD.replace('master', 'view') }),
    ],
    dependencies: [{ view_name: 'v_coffee', depends_on: 'coffees', depends_on_type: 'table' as const }],
    firestoreBlock: '-- ── Firestore ──\n-- firestore: users/{uid} | Purpose: x',
    databaseName: 'axisandbloom_test',
    generatedOn: '2026-10-16',
  };

  it('is deterministic and ends with the hash footer the boot check reads', () => {
    const md = renderCatalogMd(input);
    expect(renderCatalogMd(input)).toBe(md);
    expect(md.split('\n')[0]).toMatch(/^<!-- GENERATED by `npm run catalog:md`/);
    expect(CATALOG_HASH_FOOTER.exec(md)?.[1]).toBe(computeCatalogHash(input.rows));
    expect(md).toContain('catalog:brief-3-insertion-point');
    expect(md).toContain('Id. \\| Writer: seed'); // pipes escaped inside table cells
    expect(md).toContain('- **reads:** `coffees`');
  });

  it('readCatalogMdHash returns null for a missing file', () => {
    expect(readCatalogMdHash('C:/does/not/exist/CATALOG.md')).toBeNull();
  });

  it('extractFirestoreBlock copies the -- block under the Firestore header verbatim', () => {
    const sql = '-- header\n\n-- ── Firestore (x) ──\n-- a\n-- firestore: b | c\n\n-- ── next ──\n';
    expect(extractFirestoreBlock(sql)).toBe('-- ── Firestore (x) ──\n-- a\n-- firestore: b | c');
  });
});

// Data catalog brief 3 (2026-10-16) — the Writer field parser. The TS twin
// (boot check 5) must agree with the CI scanner (lineage-scan.mjs) on every
// table, or the boot check and CI could disagree about the one-writer rule.
describe('declaredWriterModules', () => {
  it('takes the module before the dot, splits on , and ; outside parentheses', () => {
    expect(declaredWriterModules('catalogService.createCoffee, catalogService.updateCoffee; seed; backfill:migrateSavedItems'))
      .toEqual(['backfill:migrateSavedItems', 'catalogService', 'seed']);
    expect(declaredWriterModules('apiEventLog.apiEventLog (INSERT before the handler, UPDATE at response finish), apiEventLog.writeOutcome'))
      .toEqual(['apiEventLog']);
    expect(declaredWriterModules('users.PATCH /api/users/dial-position; seed')).toEqual(['seed', 'users']);
    expect(declaredWriterModules('tokenService.spendToken; manual:grant_tokens')).toEqual(['manual:grant_tokens', 'tokenService']);
  });

  it('none, none (derived) and empty mean no writer', () => {
    expect(declaredWriterModules('none')).toEqual([]);
    expect(declaredWriterModules('none (derived)')).toEqual([]);
    expect(declaredWriterModules(null)).toEqual([]);
  });

  it('agrees with lineage-scan.mjs on every table in comments.sql', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'lineage-agree-'));
    try {
      const out = join(dir, 'lineage.json');
      await promisify(execFile)('node', [fileURLToPath(new URL('../../scripts/lineage-scan.mjs', import.meta.url))], { env: { ...process.env, LINEAGE_OUT: out } });
      const tables = JSON.parse(readFileSync(out, 'utf8')).tables as Record<string, { declared: { field: string; modules: string[] } }>;
      expect(Object.keys(tables).length).toBeGreaterThan(100);
      for (const [t, v] of Object.entries(tables)) expect(declaredWriterModules(v.declared.field), t).toEqual(v.declared.modules);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
