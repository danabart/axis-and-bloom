// Data catalog · brief 2, Part C (2026-10-16) — renders CATALOG.md from the
// live dictionary (v_data_catalog + v_data_view_dependency) and the
// Firestore block of db/comments.sql. Pure: same inputs, same bytes. The
// only moving part is `generatedOn`; scripts/catalogMd.ts leaves an existing
// file untouched when its catalog-hash already matches, so a regenerate with
// no schema or comment change produces no diff.
import type { CatalogRow, ViewDependency } from './dataCatalogQueries.js';
import { computeCatalogHash, parseRelationComment } from './dataCatalogQueries.js';

export const CATALOG_MD_FIRST_LINE =
  '<!-- GENERATED by `npm run catalog:md` (backend/src/scripts/catalogMd.ts) from the database. Do not edit by hand; edit backend/src/db/comments.sql and regenerate. -->';
export const LINEAGE_INSERTION_POINT =
  '<!-- catalog:brief-3-insertion-point — data catalog brief 3 appends its "Lineage" and "Table activity" sections here. -->';

const TABLE_CLASS_ORDER = ['master', 'fact', 'operating', 'snapshot', 'deprecated'];

// The Firestore block at the top of comments.sql: from the "── Firestore"
// header line through the end of that run of `--` lines, verbatim.
export function extractFirestoreBlock(commentsSql: string): string {
  const lines = commentsSql.split(/\r?\n/);
  const start = lines.findIndex(l => l.startsWith('-- ── Firestore'));
  if (start < 0) return '';
  const out: string[] = [];
  for (let i = start; i < lines.length && lines[i].startsWith('--'); i++) out.push(lines[i]);
  return out.join('\n');
}

const cell = (s: string | null | undefined) => (s ?? '').replace(/\|/g, '\\|');

export interface RenderInput {
  rows: CatalogRow[];
  dependencies: ViewDependency[];
  firestoreBlock: string;
  databaseName: string;
  generatedOn: string; // YYYY-MM-DD (UTC)
}

export function renderCatalogMd({ rows, dependencies, firestoreBlock, databaseName, generatedOn }: RenderInput): string {
  const hash = computeCatalogHash(rows);
  const relations = rows.filter(r => r.object_type !== 'column');
  const tables = relations.filter(r => r.object_type === 'table');
  const views = relations.filter(r => r.object_type === 'view');
  const columns = rows.filter(r => r.object_type === 'column');
  const byName = (a: CatalogRow, b: CatalogRow) => (a.table_name < b.table_name ? -1 : a.table_name > b.table_name ? 1 : 0);

  const out: string[] = [];
  out.push(CATALOG_MD_FIRST_LINE, '');
  out.push('# Data catalog', '');
  out.push(`Generated ${generatedOn} from database \`${databaseName}\` · ${tables.length} tables · ${views.length} views · ${columns.length} table columns · ` +
    `${rows.filter(r => r.is_unverified).length} UNVERIFIED · lint: report only · catalog-hash \`${hash.slice(0, 12)}\` (full value in the footer).`, '');
  out.push('The database describes itself: every description below is a Postgres `COMMENT ON`, kept in `backend/src/db/comments.sql` ' +
    'and applied at every boot. History and the why stay in `WHAT_WE_BUILT_DB.md`; this file is the what, now.', '');

  out.push('## Read before proposing a new table', '');
  out.push('> Any brief that creates, alters or drops a table, view or column ends by running `npm run catalog:md` and committing the result. ' +
    'Before proposing any new table or view, read `CATALOG.md` and state in the brief why no existing object fits. ' +
    '(Dana, 2026-10-13: "before proposing any new table, check what already exists and say why it doesn\'t fit.")', '');

  out.push('## Firestore', '', 'Copied verbatim from the top of `backend/src/db/comments.sql`.', '', '```text', firestoreBlock, '```', '');

  out.push('## Tables', '');
  const classOf = (r: CatalogRow) => (r.comment ? parseRelationComment(r.comment).class : null) ?? 'unclassified';
  const groups = [...TABLE_CLASS_ORDER, ...[...new Set(tables.map(classOf))].filter(c => !TABLE_CLASS_ORDER.includes(c)).sort()];
  for (const cls of groups) {
    const members = tables.filter(t => classOf(t) === cls).sort(byName);
    if (members.length === 0) continue;
    out.push(`### ${cls} (${members.length})`, '');
    for (const t of members) {
      const p = parseRelationComment(t.comment ?? '');
      out.push(`#### \`${t.table_name}\``, '');
      if (p.unverified) out.push(`**UNVERIFIED:** ${(t.comment ?? '').split(' | ')[0].replace(/^UNVERIFIED:?\s*/, '')}`, '');
      out.push(p.purpose ?? '_(no purpose)_', '');
      out.push(`- **Writer:** ${p.writer ?? '—'}`, `- **Readers:** ${p.readers ?? '—'}`, `- **Since:** ${p.since ?? '—'}`, '');
      out.push('| column | type | null | comment |', '|---|---|---|---|');
      for (const c of columns.filter(c => c.table_name === t.table_name)) {
        out.push(`| \`${c.column_name}\` | ${cell(c.data_type)} | ${c.is_nullable ? 'yes' : 'no'} | ${cell(c.comment)} |`);
      }
      out.push('');
    }
  }

  out.push('## Views', '');
  for (const v of [...views].sort(byName)) {
    const p = parseRelationComment(v.comment ?? '');
    const reads = dependencies.filter(d => d.view_name === v.table_name).map(d => `\`${d.depends_on}\``);
    out.push(`#### \`${v.table_name}\``, '');
    if (p.unverified) out.push(`**UNVERIFIED:** ${(v.comment ?? '').split(' | ')[0].replace(/^UNVERIFIED:?\s*/, '')}`, '');
    out.push(p.purpose ?? '_(no purpose)_', '');
    out.push(`- **Writer:** ${p.writer ?? '—'}`, `- **Readers:** ${p.readers ?? '—'}`, `- **Since:** ${p.since ?? '—'}`,
      `- **reads:** ${reads.length ? reads.join(', ') : '—'}`, '');
  }

  out.push(LINEAGE_INSERTION_POINT, '');
  out.push('---', '', `catalog-hash: ${hash}`, '');
  return out.join('\n');
}
